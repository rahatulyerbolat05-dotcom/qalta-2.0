// After `vite build`:
//  1. writes solid-colour iOS launch images (the colour the launch layer starts from);
//  2. adds the CSP with a hash of the inline boot script;
//  3. writes the service worker with the exact list of files to cache;
//  4. fails the build if the first screen's JavaScript is over budget.
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';

const DIST = path.resolve('dist');
const LAUNCH = [0xf4, 0xef, 0xe6]; // Dawn #F4EFE6 — must match --dawn and manifest background_color
const BUDGET_JS_GZIP = 80 * 1024;

// ── 1. launch images ────────────────────────────────────────────────
// [css width, css height, pixel ratio] for current iPhones, portrait.
const DEVICES = [
  [440, 956, 3], [402, 874, 3], [430, 932, 3], [393, 852, 3], [428, 926, 3],
  [390, 844, 3], [375, 812, 3], [414, 896, 3], [414, 896, 2], [375, 667, 2],
];

function crc32(buf) {
  let c = ~0;
  for (const b of buf) {
    c ^= b;
    for (let k = 0; k < 8; k++) c = (c >>> 1) ^ (0xedb88320 & -(c & 1));
  }
  return ~c >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}
function solidPng(w, h, [r, g, b]) {
  const row = Buffer.alloc(1 + w * 3);
  for (let x = 0; x < w; x++) row.set([r, g, b], 1 + x * 3);
  const raw = Buffer.alloc(row.length * h);
  for (let y = 0; y < h; y++) row.copy(raw, y * row.length);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr.set([8, 2, 0, 0, 0], 8);
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}

fs.mkdirSync(path.join(DIST, 'splash'), { recursive: true });
const links = [];
for (const [w, h, r] of DEVICES) {
  const name = `splash/launch-${w * r}x${h * r}.png`;
  fs.writeFileSync(path.join(DIST, name), solidPng(w * r, h * r, LAUNCH));
  links.push(`<link rel="apple-touch-startup-image" href="./${name}" media="(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${r}) and (orientation: portrait)">`);
}

// ── 2. CSP ──────────────────────────────────────────────────────────
const htmlPath = path.join(DIST, 'index.html');
let html = fs.readFileSync(htmlPath, 'utf8');
const inline = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => `'sha256-${crypto.createHash('sha256').update(m[1]).digest('base64')}'`);
const csp = [
  "default-src 'self'",
  `script-src 'self' ${inline.join(' ')} https://apis.google.com`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: https://lh3.googleusercontent.com",
  "font-src 'self'",
  // Google sign-in and Firestore (loaded only after the first screen)
  "connect-src 'self' https://identitytoolkit.googleapis.com https://securetoken.googleapis.com https://firestore.googleapis.com https://www.googleapis.com https://firebaseinstallations.googleapis.com",
  "frame-src https://qalta-by-yerbo.firebaseapp.com https://*.web.app https://accounts.google.com https://apis.google.com",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join('; ');
html = html.replace('<!--CSP-->', `<meta http-equiv="Content-Security-Policy" content="${csp}">`).replace('<!--SPLASH-->', links.join('\n'));
fs.writeFileSync(htmlPath, html);

// ── 3. service worker ───────────────────────────────────────────────
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
}
const files = walk(DIST)
  .map((f) => path.relative(DIST, f).split(path.sep).join('/'))
  .filter((f) => !f.startsWith('splash/') && f !== 'sw.js' && f !== 'cat-model.json');
const version = crypto.createHash('sha256').update(files.map((f) => f + fs.readFileSync(path.join(DIST, f)).length).join('|')).digest('hex').slice(0, 12);
const sw = `// Generated by tools/postbuild.mjs. Cache-first shell: the app opens without the network.
const CACHE = 'qalta-${version}';
const SHELL = ${JSON.stringify(['./', ...files.map((f) => './' + f)])};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: req.mode === 'navigate' }).then((hit) => {
      const net = fetch(req).then((res) => {
        if (res.ok && res.type === 'basic') caches.open(CACHE).then((c) => c.put(req, res.clone()));
        return res;
      });
      return hit || net.catch(() => caches.match('./'));
    })
  );
});
`;
fs.writeFileSync(path.join(DIST, 'sw.js'), sw);

// ── 4. budget ───────────────────────────────────────────────────────
const entryJs = [...html.matchAll(/<script type="module"[^>]*src="\.\/([^"]+)"/g), ...html.matchAll(/<link rel="modulepreload"[^>]*href="\.\/([^"]+)"/g)].map((m) => m[1]);
let total = 0;
for (const f of entryJs) {
  const gz = zlib.gzipSync(fs.readFileSync(path.join(DIST, f)), { level: 9 }).length;
  total += gz;
  console.log(`  ${f}: ${(gz / 1024).toFixed(1)} KB gzip`);
}
const htmlGz = zlib.gzipSync(html, { level: 9 }).length;
console.log(`  index.html: ${(htmlGz / 1024).toFixed(1)} KB gzip`);
console.log(`First-screen JavaScript: ${(total / 1024).toFixed(1)} KB gzip (budget ${BUDGET_JS_GZIP / 1024} KB)`);
console.log(`Service worker caches ${files.length + 1} files, version ${version}; ${links.length} launch images.`);
if (!entryJs.length) {
  console.error('No entry script found in dist/index.html');
  process.exit(1);
}
if (total > BUDGET_JS_GZIP) {
  console.error('Over budget: the first screen must stay fast to open.');
  process.exit(1);
}
